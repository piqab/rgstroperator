#!/bin/sh
# Assembles deploy/operator.yaml (everything needed to install the
# operator with one kubectl apply) from the generated CRD and RBAC and the
# hand-written manager manifests. The image tag is the VERSION file.
set -e
cd "$(dirname "$0")/.."
version=$(cat VERSION)
{
  echo "# rgstroperator v${version} — generated by 'make bundle', do not edit."
  echo "# kubectl apply -f https://github.com/piqab/rgstroperator/releases/download/v${version}/operator.yaml"
  for f in config/crd/bases/registry.rgstr.io_registries.yaml \
           config/manager/namespace.yaml \
           config/manager/serviceaccount.yaml \
           config/rbac/role.yaml \
           config/rbac/role_binding.yaml \
           config/manager/manager.yaml; do
    echo "---"
    sed -e '/^---$/d' -e "s|ghcr.io/piqab/rgstroperator:VERSION|ghcr.io/piqab/rgstroperator:${version}|" "$f"
  done
} > deploy/operator.yaml

# The Helm chart takes the same CRD and RBAC rules.
chart=charts/rgstroperator
cp config/crd/bases/registry.rgstr.io_registries.yaml "$chart/crds/"
{
  echo "# Generated by 'make bundle' from config/rbac/role.yaml, do not edit."
  sed -e '/^---$/d' \
      -e 's|^  name: rgstroperator-manager-role$|  name: {{ include "rgstroperator.name" . }}\n  labels: {{- include "rgstroperator.labels" . \| nindent 4 }}|' \
      config/rbac/role.yaml
} > "$chart/templates/clusterrole.yaml"
sed -i -e "s/^version: .*/version: ${version}/" -e "s/^appVersion: .*/appVersion: \"${version}\"/" "$chart/Chart.yaml"
